#!/usr/bin/env python3
"""Regenerate the profile panel images used in README.md.

Writes .github/readme/profile-panel-{light,dark}.svg with site/public/photo.jpg
embedded, so the README shows the same panel as timothestoifl24.dev.
Run from anywhere:  python3 scripts/readme-panel.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME = "Timothé Stoifl"
ROLE = "IT System Engineer &amp; Hobby Developer"
FONT = "Inter, -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif"

# Colours match the VitePress default theme (light / dark).
THEMES = {
    "light": dict(bg="#ffffff", border="#e2e2e3", name="#1b1b1f", role="#67676c", shadow=0.10),
    "dark": dict(bg="#202127", border="#2e2e32", name="#dfdfd6", role="#98989f", shadow=0.40),
}


def panel(photo_b64: str, bg: str, border: str, name: str, role: str, shadow: float) -> str:
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 560 176" width="560" height="176" role="img" aria-label="{NAME}, {ROLE}">
  <!-- Generated by scripts/readme-panel.py; edit that script, not this file. -->
  <defs>
    <filter id="s" x="-10%" y="-20%" width="120%" height="150%">
      <feDropShadow dx="0" dy="6" stdDeviation="9" flood-color="#000" flood-opacity="{shadow}"/>
    </filter>
    <clipPath id="c"><circle cx="88" cy="86" r="56"/></clipPath>
  </defs>
  <rect x="12" y="8" width="536" height="156" rx="16" fill="{bg}" stroke="{border}" filter="url(#s)"/>
  <image x="32" y="30" width="112" height="112" clip-path="url(#c)" preserveAspectRatio="xMidYMid slice" href="data:image/jpeg;base64,{photo_b64}"/>
  <text x="168" y="82" font-family="{FONT}" font-size="32" font-weight="700" fill="{name}">{NAME}</text>
  <text x="168" y="114" font-family="{FONT}" font-size="18" fill="{role}">{ROLE}</text>
</svg>
"""


def main() -> None:
    photo = base64.b64encode((ROOT / "site/public/photo.jpg").read_bytes()).decode()
    out_dir = ROOT / ".github/readme"
    out_dir.mkdir(parents=True, exist_ok=True)
    for theme, colours in THEMES.items():
        out = out_dir / f"profile-panel-{theme}.svg"
        out.write_text(panel(photo, **colours), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
